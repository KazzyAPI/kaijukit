#!/usr/bin/env python3 -I
"""Generate structural API specs (params, bodies, responses, scopes, schemas) from the pinned public OpenAPI files.
Structure only: free-text descriptions are not copied (clean-room policy).
usage: confluence_api_spec.py <v1.json> <v2.json>   -> docs/parity/confluence-api/{v1,v2}/*.md
"""
import json, os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs/parity/confluence-api")
M = ("get", "post", "put", "delete", "patch")

def run(ver, path):
    d = json.load(open(path)); C = d.get("components", {})
    def res(o):
        while isinstance(o, dict) and "$ref" in o:
            o = C[o["$ref"].split("/")[2]][o["$ref"].split("/")[3]]
        return o
    def t(s, depth=0):
        if not isinstance(s, dict): return "any"
        if "$ref" in s: return f"`{s['$ref'].split('/')[-1]}`"
        for k in ("allOf", "oneOf", "anyOf"):
            if k in s:
                j = {"allOf": " & ", "oneOf": " | ", "anyOf": " | "}[k]
                return j.join(t(x, depth) for x in s[k])
        ty = s.get("type", "object" if "properties" in s else "any")
        if ty == "array": ty = f"array<{t(s.get('items', {}), depth)}>"
        extra = []
        if "enum" in s: extra.append("enum " + "|".join(map(str, s["enum"])))
        if "format" in s: extra.append(s["format"])
        if "default" in s: extra.append(f"default {json.dumps(s['default'])}")
        if s.get("nullable"): extra.append("nullable")
        for k in ("minimum", "maximum", "minLength", "maxLength", "pattern"):
            if k in s: extra.append(f"{k} {s[k]}")
        if "additionalProperties" in s and s["additionalProperties"] not in (True, False):
            ty = f"map<string,{t(s['additionalProperties'], depth)}>"
        return ty + (f" ({', '.join(extra)})" if extra else "")
    def props(s, ind=0, depth=0):
        out = []
        if not isinstance(s, dict) or depth > 3: return out
        for k in ("allOf",):
            for x in s.get(k, []):
                if "$ref" not in x: out += props(x, ind, depth)
        req = set(s.get("required", []))
        for n, p in (s.get("properties") or {}).items():
            out.append(f"{'  '*ind}- `{n}`: {t(p)}{' **required**' if n in req else ''}")
            inner = p.get("items", p) if isinstance(p, dict) else {}
            if isinstance(inner, dict) and "$ref" not in inner and inner.get("properties"):
                out += props(inner, ind + 1, depth + 1)
        return out
    def body(s):
        s = s or {}
        return t(s) + ("" if "$ref" in s else "\n" + "\n".join(props(s, 1)) if props(s) else "")
    os.makedirs(f"{ROOT}/{ver}", exist_ok=True)
    tags = {}
    for p, v in d["paths"].items():
        for m, op in v.items():
            if m in M: tags.setdefault((op.get("tags") or ["Untagged"])[0], []).append((p, m, op, v.get("parameters", [])))
    for tag, items in sorted(tags.items()):
        L = [f"# Confluence REST {ver}: {tag}", "", "Last reviewed: 2026-11-24 · generated by `scripts/confluence_api_spec.py` · structure from the pinned public spec; see [../../confluence-rest-{ver}.md](../../confluence-rest-{ver}.md) for status.".replace("{ver}", ver), ""]
        for p, m, op, shared in sorted(items, key=lambda x: (x[0], x[1])):
            L += [f"## {m.upper()} `{p}`", "", f"`{op.get('operationId','')}` — {op.get('summary','')}", ""]
            ps = [res(x) for x in shared + op.get("parameters", [])]
            if ps:
                L += ["| Param | In | Type | Req |", "|---|---|---|---|"]
                L += [f"| `{x['name']}` | {x['in']} | {t(x.get('schema', {})).replace('|', '/')} | {'yes' if x.get('required') else ''} |" for x in ps]
                L.append("")
            rb = res(op.get("requestBody"))
            if rb:
                for ct, c in rb.get("content", {}).items():
                    L += [f"**Body** `{ct}`{' (required)' if rb.get('required') else ''}: {body(c.get('schema'))}", ""]
            L.append("**Responses:**")
            for code, r in op.get("responses", {}).items():
                r = res(r); cs = r.get("content") or {}
                sch = "; ".join(f"`{ct}` {body(c.get('schema'))}" for ct, c in cs.items() if c.get("schema"))
                L.append(f"- `{code}`" + (f": {sch}" if sch else ""))
            sc = sorted({s for sec in op.get("security", []) for k, v in sec.items() if k != "basicAuth" for s in v})
            L += ["", f"**Scopes:** {', '.join(f'`{s}`' for s in sc) if sc else 'none listed'}", ""]
        open(f"{ROOT}/{ver}/{re.sub(r'[^a-z0-9]+', '-', tag.lower()).strip('-')}.md", "w").write("\n".join(L))
    L = [f"# Confluence REST {ver}: schemas", "", "Last reviewed: 2026-11-24 · generated · structure only.", ""]
    for n, s in sorted(C.get("schemas", {}).items()):
        L += [f"## {n}", "", t(s) if not s.get("properties") else "object", ""] + props(s) + [""]
    sec = C.get("securitySchemes", {})
    L += ["## Security schemes", "", "```json", json.dumps(sec, indent=1), "```", ""]
    open(f"{ROOT}/{ver}/_schemas.md", "w").write("\n".join(L))
    print(ver, len(tags), "tags,", len(C.get("schemas", {})), "schemas")

run("v1", sys.argv[1]); run("v2", sys.argv[2])
