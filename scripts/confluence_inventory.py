#!/usr/bin/env python3 -I
"""Generate/check docs/parity/confluence-rest-v{1,2}.md from the pinned public OpenAPI specs.

  confluence_inventory.py gen   <v1.json> <v2.json>   rewrite inventories, keeping Status/Case of existing rows
  confluence_inventory.py check <v1.json> <v2.json>   fail if spec and inventory differ, or a `done` row has no case
"""
import hashlib, json, re, sys, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SPECS = {  # pinned: URL + sha256 of the snapshot reviewed on 2026-11-24
    "v1": ("https://dac-static.atlassian.com/cloud/confluence/swagger.v3.json", "/wiki/rest/api",
           "f80279e4beace901a20174044ff3dc1cf047ea9486c3dd6eff57e33e4161bf12"),
    "v2": ("https://dac-static.atlassian.com/cloud/confluence/openapi-v2.v3.json", "/wiki/api/v2",
           "40535e2a2c01547d53d824d68299098c9073e5bf7ed98a71634706759becfa31"),
}
M = ("get", "post", "put", "delete", "patch")

def ops(path):
    raw = open(path, "rb").read()
    return hashlib.sha256(raw).hexdigest(), [
        (m.upper(), p, (o.get("tags") or ["Untagged"])[0], o.get("operationId", ""), (o.get("summary") or "").replace("|", "/"))
        for p, v in json.loads(raw)["paths"].items() for m, o in v.items() if m in M]

def old_rows(f):
    if not os.path.exists(f): return {}
    return {(m[1], m[2]): (m[3], m[4]) for m in
            (re.match(r"\| (\w+) \| `([^`]+)` \| .*\| (\S[^|]*?) \| ([^|]*?) \|$", l) for l in open(f)) if m}

def main(mode, files):
    bad = 0
    for ver, f in zip(("v1", "v2"), files):
        url, base, pin = SPECS[ver]
        sha, rows = ops(f)
        if sha != pin: sys.exit(f"{ver}: spec sha {sha} != pinned {pin}; re-review and update pin")
        out = os.path.join(ROOT, f"docs/parity/confluence-rest-{ver}.md")
        old = old_rows(out)
        if mode == "check":
            if {(m, p) for m, p, *_ in rows} != set(old): print(f"{ver}: inventory out of sync with spec"); bad = 1
            for k, (st, case) in old.items():
                if st == "done" and not case.strip(" -"): print(f"{ver}: {k} is done without a conformance case"); bad = 1
            continue
        L = [f"# Confluence Cloud REST {ver} — operation inventory", "", "Last reviewed: 2026-11-24", "",
             f"Source: <{url}> (sha256 `{pin}`). Base path `{base}`. Generated by `scripts/confluence_inventory.py`; edit only Status and Case.",
             "Status: `not started` | `partial` | `partial (schema)` (passes schema-mode conformance only) | `done` (diff-mode case against a reference). `done` requires a conformance case. Behavior notes go in [confluence-parity.md](confluence-parity.md).", ""]
        tag = None
        for m, p, t, oid, s in sorted(rows, key=lambda r: (r[2], r[1], r[0])):
            if t != tag:
                L += ["", f"## {t}", "", "| Method | Path | operationId | Summary | Status | Case |", "|---|---|---|---|---|---|"]; tag = t
            st, case = old.get((m, p), ("not started", "-"))
            L.append(f"| {m} | `{p}` | `{oid}` | {s} | {st} | {case} |")
        open(out, "w").write("\n".join(L) + "\n")
        print(ver, len(rows), "operations")
    sys.exit(bad)

if __name__ == "__main__" and len(sys.argv) == 4 and sys.argv[1] in ("gen", "check"):
    main(sys.argv[1], sys.argv[2:])
else: sys.exit(__doc__)
